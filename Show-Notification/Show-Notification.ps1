<#
.SYNOPSIS
    Shows Windows toast notifications and manages notification templates, queueing,
    preferences, history, and scheduled recurrence.

.DESCRIPTION
    A notification library built on the Windows 10+ toast API. When invoked with
    -Template and -VariablesJson (as generated by Schedule-RecurringNotification)
    it sends a single templated notification and exits.

.EXAMPLE
    .\Show-Notification.ps1
    Defines the notification functions for the session (library mode).

.EXAMPLE
    .\Show-Notification.ps1 -Template SoftwareUpdate -VariablesJson '{"Name":"Teams","Version":"1.6"}'

.NOTES
    Version: 3.0
    Author: Claudio Gonçalves
#>

#Requires -Version 5.1

